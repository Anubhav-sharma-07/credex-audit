import type { AIQuestionContext } from "./types";

export interface PostValidationResult {
  isValid: boolean;
  rejectedNumbers: number[];
  allowedNumbers: number[];
  citedFindingIds: string[];
  rejectionReason?: string;
}

/**
 * Extracts all numeric values from text (integers, decimals, currency values, percentages).
 */
export function extractNumbersFromText(text: string): number[] {
  // Matches: $1,234.56, $50, 25%, 10.5, 42
  const regex = /(?:\$)?\b\d{1,3}(?:,\d{3})*(?:\.\d+)?%?\b/g;
  const matches = text.match(regex) || [];
  const numbers: number[] = [];

  for (const m of matches) {
    // Strip $, %, and commas
    const clean = m.replace(/[$,%]/g, "");
    const num = parseFloat(clean);
    if (!isNaN(num)) {
      numbers.push(num);
    }
  }

  return numbers;
}

/**
 * Gathers the complete set of legitimate, evidence-backed numbers present in the input.
 */
export function computeAllowedInputNumbers(ctx: AIQuestionContext): Set<number> {
  const allowed = new Set<number>();

  const add = (n: number | null | undefined) => {
    if (n !== null && n !== undefined && !isNaN(n)) {
      allowed.add(n);
      allowed.add(Math.round(n));
      // Also allow 12x annualized
      allowed.add(n * 12);
      allowed.add(Math.round(n * 12));
    }
  };

  // Standard renewal and audit review window thresholds (days)
  [7, 14, 30, 60, 90, 180, 365].forEach((d) => allowed.add(d));

  add(ctx.monthlySpendUsd);
  add(ctx.monthlySavingsUsd);
  add(ctx.teamSize);
  if (ctx.budgetMonthlyUsd) {
    add(ctx.budgetMonthlyUsd);
    add(Math.abs(ctx.monthlySpendUsd - ctx.budgetMonthlyUsd)); // overrun / delta
  }

  for (const f of ctx.findings) {
    add(f.currentMonthlyUsd);
    add(f.projectedMonthlyUsd);
    add(f.savingsMonthlyUsd);

    // Parse any numbers mentioned in evidence statements
    for (const ev of f.evidenceSummary) {
      const nums = extractNumbersFromText(ev);
      nums.forEach((n) => add(n));
    }
  }

  return allowed;
}

/**
 * Extracts finding citations matching format [finding_id] or [sub_...].
 */
export function extractCitations(text: string, validFindingIds: Set<string>): string[] {
  const regex = /\[([a-zA-Z0-9_\-]+)\]/g;
  const citations = new Set<string>();
  let match: RegExpExecArray | null;

  while ((match = regex.exec(text)) !== null) {
    const id = match[1];
    if (validFindingIds.has(id)) {
      citations.add(id);
    }
  }

  return Array.from(citations);
}

/**
 * Post-check numerical validation.
 * Rejects any number generated by the LLM that was not supplied in the structured input.
 */
export function validateAIOutput(
  output: string,
  ctx: AIQuestionContext
): PostValidationResult {
  const allowedSet = computeAllowedInputNumbers(ctx);
  const outputNumbers = extractNumbersFromText(output);
  const rejectedNumbers: number[] = [];

  for (const num of outputNumbers) {
    // Check with tolerance for rounding
    const matched = Array.from(allowedSet).some(
      (allowed) => Math.abs(allowed - num) < 0.01
    );
    if (!matched) {
      rejectedNumbers.push(num);
    }
  }

  const validFindingIds = new Set(ctx.findings.map((f) => f.id));
  const citedFindingIds = extractCitations(output, validFindingIds);

  if (rejectedNumbers.length > 0) {
    return {
      isValid: false,
      rejectedNumbers,
      allowedNumbers: Array.from(allowedSet),
      citedFindingIds,
      rejectionReason: `Hallucinated numbers detected not present in input context: ${rejectedNumbers.join(", ")}`,
    };
  }

  // Ensure output includes at least one valid citation when findings exist
  if (ctx.findings.length > 0 && citedFindingIds.length === 0) {
    return {
      isValid: false,
      rejectedNumbers: [],
      allowedNumbers: Array.from(allowedSet),
      citedFindingIds: [],
      rejectionReason: `Missing required finding citation [finding-id] in response.`,
    };
  }

  return {
    isValid: true,
    rejectedNumbers: [],
    allowedNumbers: Array.from(allowedSet),
    citedFindingIds,
  };
}
